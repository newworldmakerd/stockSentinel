CREATE TABLE t_trade_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    root_id BIGINT,
    message_hash VARCHAR(64) NOT NULL UNIQUE,
    group_hash VARCHAR(64) NOT NULL,user_id VARCHAR(256) NOT NULL,symbol VARCHAR(12) NOT NULL,trade_date DATE NOT NULL,
    kind VARCHAR(12) NOT NULL CHECK(kind IN ('FILL','CORRECT','VOID')),
    side VARCHAR(4) NOT NULL CHECK(side IN ('BUY','SELL')),
    quantity BIGINT,price NUMERIC(18,4),
    origin VARCHAR(24) NOT NULL DEFAULT 'USER_REPORTED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(id,group_hash,user_id,symbol,trade_date),
    FOREIGN KEY(group_hash,user_id,symbol,trade_date) REFERENCES t_observation_day,
    FOREIGN KEY(root_id,group_hash,user_id,symbol,trade_date) REFERENCES t_trade_event(id,group_hash,user_id,symbol,trade_date),
    CHECK((kind='FILL' AND root_id IS NULL) OR (kind IN ('CORRECT','VOID') AND root_id IS NOT NULL)),
    CHECK((kind='VOID' AND quantity IS NULL AND price IS NULL) OR (kind<>'VOID' AND quantity BETWEEN 1 AND 1000000000 AND price>0))
);
CREATE INDEX ix_t_trade_scope ON t_trade_event(group_hash,user_id,symbol,trade_date,id);
CREATE INDEX ix_t_trade_root ON t_trade_event(root_id,id DESC);
INSERT INTO t_trade_event(message_hash,group_hash,user_id,symbol,trade_date,kind,side,quantity,price,origin,created_at)
SELECT message_hash,group_hash,user_id,symbol,trade_date,'FILL',side,quantity,price,'LEGACY_AGGREGATE',recorded_at
FROM t_observation_receipt ORDER BY recorded_at,message_hash;
COMMENT ON TABLE t_trade_event IS 'Append-only user declarations, corrections and voids; no order execution or inferred broker holdings';
