CREATE TABLE scan_fault_state (
    destination_hash VARCHAR(64) NOT NULL,
    failure_kind VARCHAR(40) NOT NULL,
    streak INT NOT NULL DEFAULT 0 CHECK (streak >= 0),
    active BOOLEAN NOT NULL DEFAULT false,
    incident_id VARCHAR(36),
    last_job_id BIGINT NOT NULL DEFAULT 0,
    last_scan_at TIMESTAMPTZ,
    last_alert_at TIMESTAMPTZ,
    seq BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (destination_hash, failure_kind)
);

CREATE TABLE scan_fault_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_hash VARCHAR(64) NOT NULL,
    failure_kind VARCHAR(40) NOT NULL,
    incident_id VARCHAR(36) NOT NULL,
    seq BIGINT NOT NULL,
    event_type VARCHAR(12) NOT NULL CHECK (event_type IN ('FAULT','RECOVERY')),
    job_id BIGINT NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','SENDING','SUCCESS','UNKNOWN','FAILED','RETRY','EXPIRED','CANCELLED')),
    attempts INT NOT NULL DEFAULT 0,
    claim_token VARCHAR(36), lease_until TIMESTAMPTZ, next_retry_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), sent_at TIMESTAMPTZ, last_error VARCHAR(60),
    UNIQUE (destination_hash, failure_kind, seq)
);
CREATE INDEX idx_scan_fault_pending ON scan_fault_event(destination_hash, status, id);
CREATE INDEX idx_scan_fault_incident ON scan_fault_event(destination_hash, failure_kind, incident_id);
