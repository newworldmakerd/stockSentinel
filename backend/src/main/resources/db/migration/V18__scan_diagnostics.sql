CREATE TABLE scan_step (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES job_execution(id),
    symbol VARCHAR(12) NOT NULL REFERENCES stock_info(symbol),
    stage VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK(status IN ('SUCCESS','SKIPPED','FAILED')),
    code VARCHAR(80) NOT NULL,
    source VARCHAR(40),
    data_observed_at TIMESTAMPTZ,
    data_basis_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ NOT NULL,
    elapsed_ms BIGINT NOT NULL CHECK(elapsed_ms>=0)
);
CREATE INDEX ix_scan_step_job ON scan_step(job_id,id);
CREATE INDEX ix_scan_step_symbol ON scan_step(symbol,id DESC);
CREATE TABLE scan_signal_link (
    job_id BIGINT NOT NULL REFERENCES job_execution(id),
    signal_id BIGINT NOT NULL REFERENCES signal_event(id),
    PRIMARY KEY(job_id,signal_id)
);
