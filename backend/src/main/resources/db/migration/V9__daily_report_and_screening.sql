CREATE TABLE market_screen_run (
    trade_date DATE PRIMARY KEY, as_of DATE NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'RUNNING',
    total INT NOT NULL, overview JSONB, started_at TIMESTAMPTZ NOT NULL DEFAULT now(), finished_at TIMESTAMPTZ
);
CREATE TABLE market_screen_item (
    trade_date DATE NOT NULL REFERENCES market_screen_run(trade_date),
    symbol VARCHAR(12) NOT NULL REFERENCES stock_info(symbol), status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    code VARCHAR(60), average_amount NUMERIC(24,4), details JSONB, explanation VARCHAR(1000),
    PRIMARY KEY(trade_date,symbol)
);
CREATE INDEX idx_screen_status ON market_screen_item(trade_date,status);
CREATE TABLE daily_group_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, trade_date DATE NOT NULL,
    destination_hash VARCHAR(64) NOT NULL, payload TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INT NOT NULL DEFAULT 0, claim_token VARCHAR(36), lease_until TIMESTAMPTZ, next_retry_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), sent_at TIMESTAMPTZ, last_error VARCHAR(60),
    UNIQUE(trade_date,destination_hash)
);
