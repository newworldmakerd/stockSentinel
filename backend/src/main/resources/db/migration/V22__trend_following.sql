CREATE TABLE trend_follow_item (
    as_of DATE NOT NULL, symbol VARCHAR(12) NOT NULL REFERENCES stock_info(symbol),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','READY','EXCLUDED','FAILED')),
    code VARCHAR(60), attempts INT NOT NULL DEFAULT 0, next_retry_at TIMESTAMPTZ, metrics JSONB,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(as_of,symbol)
);
CREATE TABLE trend_follow_index (as_of DATE PRIMARY KEY, snapshot JSONB NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE trend_follow_runtime (name VARCHAR(40) PRIMARY KEY, snapshot JSONB NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE trend_follow_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, symbol VARCHAR(12) NOT NULL REFERENCES stock_info(symbol),
    trade_date DATE NOT NULL, phase VARCHAR(20) NOT NULL CHECK(phase IN ('PREVIEW','CONFIRMED')),
    snapshot JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(symbol,trade_date,phase)
);
CREATE TABLE trend_follow_account (
    group_hash VARCHAR(64) NOT NULL, user_id VARCHAR(256) NOT NULL,
    equity NUMERIC(24,4) NOT NULL CHECK(equity>0), market_value NUMERIC(24,4) NOT NULL CHECK(market_value>=0 AND market_value<=equity),
    reported_on DATE NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(group_hash,user_id)
);
CREATE TABLE trend_follow_lot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, group_hash VARCHAR(64) NOT NULL, user_id VARCHAR(256) NOT NULL,
    symbol VARCHAR(12) NOT NULL REFERENCES stock_info(symbol), entry_date DATE NOT NULL, entry_at TIMESTAMPTZ NOT NULL,
    entry_price NUMERIC(18,4) NOT NULL CHECK(entry_price>0), quantity BIGINT NOT NULL CHECK(quantity>0),
    remaining BIGINT NOT NULL CHECK(remaining>=0 AND remaining<=quantity),
    initial_atr NUMERIC(24,8), initial_stop NUMERIC(24,8), stop_price NUMERIC(24,8), stop_as_of DATE,
    highest_close NUMERIC(18,4), last_close_date DATE, atr_snapshot JSONB,
    status VARCHAR(30) NOT NULL CHECK(status IN ('ACTIVE','PENDING_DATA','CLOSED','BASIS_REVIEW')),
    CHECK((status IN ('PENDING_DATA','CLOSED','BASIS_REVIEW')) OR (initial_atr IS NOT NULL AND initial_stop IS NOT NULL AND stop_price IS NOT NULL AND initial_atr>0 AND initial_stop>0 AND stop_price>=initial_stop AND stop_as_of IS NOT NULL))
);
CREATE INDEX ix_trend_lot_stock ON trend_follow_lot(symbol,status);
CREATE TABLE trend_follow_trade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, lot_id BIGINT NOT NULL REFERENCES trend_follow_lot(id),
    message_hash VARCHAR(64) NOT NULL UNIQUE, side VARCHAR(4) NOT NULL CHECK(side IN ('BUY','SELL')),
    quantity BIGINT NOT NULL CHECK(quantity>0), price NUMERIC(18,4) NOT NULL CHECK(price>0), recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE trend_follow_notice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, idempotency_key VARCHAR(256) NOT NULL UNIQUE,
    target_chat_id VARCHAR(256) NOT NULL, payload TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INT NOT NULL DEFAULT 0, claim_token VARCHAR(36), lease_until TIMESTAMPTZ, next_retry_at TIMESTAMPTZ,
    last_error VARCHAR(60), created_at TIMESTAMPTZ NOT NULL DEFAULT now(), sent_at TIMESTAMPTZ
);
