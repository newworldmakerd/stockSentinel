ALTER TABLE job_execution ADD COLUMN trade_date DATE,
    ADD COLUMN trigger_type VARCHAR(20), ADD COLUMN skipped_count INT NOT NULL DEFAULT 0;
CREATE TABLE market_close_confirmation (
    trade_date DATE NOT NULL REFERENCES market_calendar(trade_date),
    source VARCHAR(40) NOT NULL,
    confirmed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(trade_date,source)
);
CREATE TABLE job_execution_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES job_execution(id),
    symbol VARCHAR(6) NOT NULL REFERENCES stock_info(symbol),
    stage VARCHAR(30) NOT NULL, status VARCHAR(20) NOT NULL, code VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_job_execution_item_job ON job_execution_item(job_id,id);
