CREATE TABLE custom_daily_strategy (
    id UUID PRIMARY KEY, current_revision INT NOT NULL, active_revision INT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE custom_daily_revision (
    strategy_id UUID NOT NULL REFERENCES custom_daily_strategy(id), revision INT NOT NULL CHECK(revision>0),
    name VARCHAR(80) NOT NULL, description VARCHAR(500) NOT NULL DEFAULT '', definition JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(strategy_id,revision)
);
ALTER TABLE custom_daily_strategy ADD CONSTRAINT fk_custom_current
    FOREIGN KEY(id,current_revision) REFERENCES custom_daily_revision(strategy_id,revision) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE custom_daily_strategy ADD CONSTRAINT fk_custom_active
    FOREIGN KEY(id,active_revision) REFERENCES custom_daily_revision(strategy_id,revision);
CREATE TABLE custom_daily_run (
    id UUID PRIMARY KEY, strategy_id UUID NOT NULL, revision INT NOT NULL, trade_date DATE NOT NULL,
    kind VARCHAR(10) NOT NULL CHECK(kind IN ('PREVIEW','SCAN')), request_id VARCHAR(64),
    request_hash CHAR(64), results JSONB NOT NULL, evaluated INT NOT NULL, skipped INT NOT NULL,
    matched INT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY(strategy_id,revision) REFERENCES custom_daily_revision(strategy_id,revision),
    UNIQUE(strategy_id,request_id)
);
CREATE TABLE custom_daily_event (
    id UUID PRIMARY KEY, strategy_id UUID NOT NULL, revision INT NOT NULL, symbol VARCHAR(12) NOT NULL REFERENCES stock_info(symbol),
    trade_date DATE NOT NULL, snapshot JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY(strategy_id,revision) REFERENCES custom_daily_revision(strategy_id,revision),
    UNIQUE(strategy_id,revision,symbol,trade_date)
);
CREATE TABLE custom_daily_notice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id UUID NOT NULL REFERENCES custom_daily_event(id),
    target_chat_id VARCHAR(256) NOT NULL, payload TEXT NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SENDING','SUCCESS','FAILED','RETRY','UNKNOWN','EXPIRED')),
    attempts INT NOT NULL DEFAULT 0, claim_token VARCHAR(36), lease_until TIMESTAMPTZ,
    next_retry_at TIMESTAMPTZ, last_error VARCHAR(80), created_at TIMESTAMPTZ NOT NULL DEFAULT now(), sent_at TIMESTAMPTZ,
    UNIQUE(event_id,target_chat_id)
);
CREATE INDEX ix_custom_run_revision ON custom_daily_run(strategy_id,revision,created_at DESC);
CREATE INDEX ix_custom_notice_due ON custom_daily_notice(status,next_retry_at,id);
