CREATE TABLE signal_advice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_id BIGINT NOT NULL REFERENCES signal_event(id),
    provider VARCHAR(40) NOT NULL,
    model VARCHAR(120) NOT NULL,
    prompt_version VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('SUCCESS','FAILED')),
    input_snapshot JSONB NOT NULL,
    advice JSONB,
    error_code VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(signal_id, provider, model, prompt_version)
);
COMMENT ON TABLE signal_advice IS 'LLM auxiliary advice; original deterministic signal remains unchanged';