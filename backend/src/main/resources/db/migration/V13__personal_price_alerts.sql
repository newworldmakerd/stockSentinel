CREATE TABLE personal_price_alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_hash VARCHAR(64) NOT NULL, user_id VARCHAR(256) NOT NULL,
    symbol VARCHAR(12) NOT NULL REFERENCES stock_info(symbol) ON DELETE CASCADE,
    enabled BOOLEAN NOT NULL DEFAULT true,
    take_profit NUMERIC(18,4) CHECK(take_profit>0), stop_loss NUMERIC(18,4) CHECK(stop_loss>0),
    revision BIGINT NOT NULL DEFAULT 1,
    take_profit_fired_on DATE, stop_loss_fired_on DATE, last_bar_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(group_hash,user_id,symbol),
    CHECK(take_profit IS NOT NULL OR stop_loss IS NOT NULL),
    CHECK(take_profit IS NULL OR stop_loss IS NULL OR stop_loss<take_profit)
);
CREATE TABLE personal_price_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id BIGINT NOT NULL REFERENCES personal_price_alert(id), revision BIGINT NOT NULL,
    group_hash VARCHAR(64) NOT NULL, event_type VARCHAR(30) NOT NULL,
    bar_at TIMESTAMPTZ NOT NULL, reference_price NUMERIC(18,4) NOT NULL,
    payload TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING', attempts INT NOT NULL DEFAULT 0,
    claim_token VARCHAR(36), lease_until TIMESTAMPTZ, next_retry_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), sent_at TIMESTAMPTZ, last_error VARCHAR(60),
    UNIQUE(config_id,revision,event_type,bar_at)
);
CREATE INDEX ix_personal_price_active ON personal_price_alert(group_hash,symbol) WHERE enabled;
CREATE INDEX ix_personal_price_delivery ON personal_price_event(group_hash,status,id);
