CREATE TABLE pullback_digest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_at TIMESTAMPTZ NOT NULL,
    destination_hash VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INT NOT NULL DEFAULT 0,
    claim_token VARCHAR(36), lease_until TIMESTAMPTZ, next_retry_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), sent_at TIMESTAMPTZ, last_error VARCHAR(60),
    UNIQUE(slot_at,destination_hash)
);
